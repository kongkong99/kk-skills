#!/usr/bin/env python3
"""Build the personal skill from one public workflow and a personal profile.

No network or editor required. --check detects stale generated files.
--dist DIR writes deterministic, self-contained ZIPs for both editions.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import zipfile

REPO = Path(__file__).resolve().parents[1]
PUBLIC = REPO / 'skills/short-video-packaging'
PROFILE = REPO / 'profiles/video-personal'
PERSONAL = REPO / 'skills/interface-explainer-motion'


def files(root):
    return {p.relative_to(root).as_posix(): p.read_bytes()
            for p in sorted(root.rglob('*')) if p.is_file()
            and not any(x.startswith('.') or x == '__pycache__'
                        for x in p.relative_to(root).parts)
            and p.suffix != '.pyc'}


def expected_personal():
    public = files(PUBLIC)
    source = public['SKILL.md'].decode('utf-8')
    front, body = source.split('---', 2)[1:]
    match = re.search(r'^version:\s*[\"\']?([0-9]+\.[0-9]+\.[0-9]+)', front, re.M)
    if not match:
        raise ValueError('Public SKILL.md requires a semantic version.')
    version = match[1]
    profile = files(PROFILE)
    if 'profile.md' not in profile:
        raise ValueError('Missing profiles/video-personal/profile.md')
    result = {name: data for name, data in profile.items() if name != 'profile.md'}
    # Keep old personal resource paths as generated aliases to common sources.
    # These must not become independently maintained implementations.
    aliases = {
        'assets/drifting-stars.html': 'assets/drifting-stars.html',
        'assets/captions/keyword-pulse.mjs': 'assets/keyword-pulse.mjs',
        'assets/sfx/mouse-click.wav': 'assets/mouse-click.wav',
        'assets/sfx/zoom-whoosh.wav': 'assets/zoom-whoosh.wav',
    }
    for personal_path, public_path in aliases.items():
        if personal_path in profile:
            raise ValueError('Common asset must be maintained in public source: ' + personal_path)
        result[personal_path] = public[public_path]
    result['personal-profile.md'] = profile['profile.md']
    result['shared/workflow.md'] = (
        '<!-- Generated from short-video-packaging/SKILL.md; edit the public source. -->\n'
        + body.lstrip()).encode()
    for name, data in public.items():
        if name != 'SKILL.md' and not name.startswith('agents/'):
            result['shared/' + name] = data
    result['SKILL.md'] = f'''---
name: interface-explainer-motion
metadata:
  version: "{version}"
  edition: "personal"
  shared_skill: "short-video-packaging"
description: Package talking-head shorts and software tutorials using the shared short-video workflow plus this user's established personal editing rules. Use for 口播剪辑、短视频包装、软件教程动画、口播配界面 and Jeff Su-inspired visual explanation.
---

# 个人视频包装

开始制作前，按顺序读取[通用主干](shared/workflow.md)和[个人配置](personal-profile.md)。两者共同组成完整流程；个人配置覆盖主干的默认选项，用户本次明确要求优先。不要只读其中一个，也不要要求用户每次选择公开版还是个人版。

通用主干负责剪辑、同步、画面组织、字幕、声音和验收；个人配置负责已确认的标题、节奏、素材、小窗、封面等固定要求。后续按这两份文档的链接读取相关细节；即使稍后读到通用默认值，已加载的个人要求仍优先。

本目录包含主干快照、个人规则及所需资源，可单独安装，不要求另装公开 Skill。WorkBuddy 或聊天生成器只在对应任务中按需使用。

## 迭代此技能

用户反馈制作问题时，在 `kongkong99/kk-skills` 的维护源中修正：通用方法归入 `skills/short-video-packaging/`，固定个人偏好归入 `profiles/video-personal/`；按仓库的 `VIDEO_SKILLS.md` 构建、验证并更新本地个人安装版。不要只改本目录而让公开主干继续保留同一问题，也不要让用户为每条反馈重新选择版本。发布或同步 GitHub 按用户授权执行。

<!-- Generated by scripts/build_video_skills.py in kongkong99/kk-skills.
Maintain generic changes in skills/short-video-packaging, and personal choices in
profiles/video-personal. Rebuild instead of editing this generated directory. -->
'''.encode()
    return version, result


def archive(root, contents, destination):
    with zipfile.ZipFile(destination, 'w', compression=zipfile.ZIP_DEFLATED,
                         compresslevel=9) as z:
        for rel, data in sorted(contents.items()):
            info = zipfile.ZipInfo(root + '/' + rel, (2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o100755 if rel.endswith('.py') else 0o100644) << 16
            z.writestr(info, data)
    with zipfile.ZipFile(destination) as z:
        if z.testzip() is not None:
            raise ValueError('ZIP CRC failure')
        assert len(z.namelist()) == len(contents)
        for rel, data in contents.items():
            assert z.read(root + '/' + rel) == data
    return {'name': destination.name, 'files': len(contents),
            'bytes': destination.stat().st_size,
            'sha256': hashlib.sha256(destination.read_bytes()).hexdigest()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--dist', type=Path)
    parser.add_argument('--release-label', help='Archive label; metadata keeps the semantic version.')
    args = parser.parse_args()
    version, expected = expected_personal()
    actual = files(PERSONAL)
    changed = sorted(k for k, v in expected.items() if actual.get(k) != v)
    extras = sorted(set(actual) - set(expected))
    if args.check:
        if changed or extras:
            print(json.dumps({'stale': changed, 'unexpected': extras}, ensure_ascii=False))
            return 1
    else:
        # Only generated shared snapshots may be removed automatically.
        unsafe = [name for name in extras if not name.startswith('shared/')]
        if unsafe:
            raise ValueError('Unexpected personal files; preserve and inspect: ' + ', '.join(unsafe))
        for name in extras:
            (PERSONAL / name).unlink()
        for name in changed:
            target = PERSONAL / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(expected[name])
    report = {'version': version, 'personalFiles': len(expected), 'changed': changed}
    if args.dist:
        args.dist.mkdir(parents=True, exist_ok=True)
        label = args.release_label or version
        if not re.fullmatch(r'[0-9]+(?:\.[0-9]+){1,2}', label):
            raise ValueError('Invalid release label')
        report['archives'] = [archive(name, data, args.dist / f'{name}-v{label}.zip')
                              for name, data in [('short-video-packaging', files(PUBLIC)),
                                                 ('interface-explainer-motion', expected)]]
        (args.dist / 'manifest.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(report, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
